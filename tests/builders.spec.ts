test('этапы, задачи, сворачивание и удаление сохраняются и не меняют сроки', async ({ page }) => {
  await page.goto('/#tasks')
  await page.getByRole('button', { name: 'Добавить этап', exact: true }).click()
  await page.getByLabel('Название этапа').fill('Проверка перед стартом')
  await page.getByRole('button', { name: 'Сохранить этап' }).click()
  await page.getByRole('button', { name: 'Переименовать этап: Проверка перед стартом' }).click()
  await page.getByLabel('Название этапа').fill('Перед стартом')
  await page.getByRole('button', { name: 'Сохранить этап' }).click()
  const move = page.getByRole('button', { name: 'Выше этап: Перед стартом', exact: true })
  await move.focus(); await page.keyboard.press('Enter')
  const snapshot = await readStore(page), sourceTask = snapshot.events[0].tasks.find((task: { title: string }) => task.title === 'Проверить оборудование')
  await page.getByLabel('Этап для задачи: Проверить оборудование', { exact: true }).selectOption({ label: 'Перед стартом' })
  const moved = (await readStore(page)).events[0].tasks.find((task: { title: string }) => task.title === 'Проверить оборудование')
  expect({ ...moved, stageId: sourceTask.stageId }).toEqual(sourceTask)
  await page.getByRole('button', { name: 'Добавить задачу в этап: Перед стартом', exact: true }).click()
  await page.getByLabel('Название задачи').fill('Проверить список участников')
  await expect(page.getByLabel('Этап задачи', { exact: true }).locator('option:checked')).toHaveText('Перед стартом')
  await page.getByRole('button', { name: 'Сохранить изменения' }).click()
  await page.getByRole('button', { name: 'Выше задачу: Проверить список участников', exact: true }).click()
  const stage = page.getByTestId('plan-stage').filter({ has: page.getByRole('heading', { name: 'Перед стартом', exact: true }) })
  await expect(stage.getByTestId('task-row').first()).toContainText('Проверить список участников')
  await page.getByRole('button', { name: 'Свернуть этап: Перед стартом', exact: true }).click()
  await page.reload()
  await expect(stage.getByTestId('task-row')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Развернуть этап: Перед стартом' })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Удалить этап: Перед стартом', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Будет удалено задач: 2')
  await expect(page.getByRole('alert')).toContainText('критических задач: 1')
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(stage).toBeVisible()
  await page.getByRole('button', { name: 'Удалить этап: Перед стартом', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить этап и задачи', exact: true }).click()
  await expect(stage).toHaveCount(0)
  expect((await readStore(page)).events[0].tasks.length).toBe(9)
})

test('свой шаблон требует новую дату, копирует план и сбрасывает факты', async ({ page }) => {
  await page.goto('/#tasks')
  const original = (await readStore(page)).events[0]
  await page.getByRole('button', { name: 'Сохранить как шаблон', exact: true }).click()
  await page.getByLabel('Название шаблона').fill('Наш мастер-класс')
  await page.getByRole('button', { name: 'Сохранить шаблон', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await page.getByLabel('Начальный план').selectOption({ label: 'Наш мастер-класс' })
  await expect(page.getByLabel('Дата мероприятия')).toHaveValue('')
  await page.getByLabel('Название мероприятия').fill('Зимний мастер-класс')
  await page.getByRole('dialog').getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('дату')
  await page.getByLabel('Дата мероприятия').fill('2026-12-20')
  await page.getByRole('dialog').getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await expect(page.getByTestId('progress')).toContainText('0 из 10')
  const store = await readStore(page), clone = store.events.find((event: { id: string }) => event.id === store.activeId)
  expect(store.events.find((event: { id: string }) => event.id === 'demo')).toEqual(original)
  expect(clone.stages.map((stage: { title: string }) => stage.title)).toEqual(original.stages.map((stage: { title: string }) => stage.title))
  expect(clone.tasks.every((task: { status: string }) => task.status === 'open')).toBeTruthy()
  expect(clone.expenses.every((expense: { paid: number; agreed: number; expected: number; plan: number }) => expense.paid === 0 && expense.agreed === 0 && expense.expected === expense.plan)).toBeTruthy()
  const oldIds = [...original.tasks, ...original.expenses, ...original.team, ...original.stages].map(item => item.id)
  expect([...clone.tasks, ...clone.expenses, ...clone.team, ...clone.stages].every(item => !oldIds.includes(item.id))).toBeTruthy()
})

test('рабочее пространство хранится отдельно, скрытый антипровал остаётся в шапке', async ({ page }) => {
  await page.goto('/')
  const storeBefore = await readStore(page)
  await page.getByRole('button', { name: 'Настроить экран', exact: true }).click()
  await page.getByRole('button', { name: 'Выше блок: Прогресс', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByLabel('Ширина блока: Бюджет', { exact: true }).selectOption('1')
  await page.getByRole('button', { name: 'Скрыть блок: Антипровал', exact: true }).click()
  await expect(page.getByTestId('risks')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Критические проблемы: 2/ })).toBeVisible()
  expect(await readStore(page)).toEqual(storeBefore)
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  const layout = await readLayout(page)
  await page.reload()
  await expect(page.getByTestId('risks')).toHaveCount(0)
  expect(await readLayout(page)).toEqual(layout)
  await page.getByRole('button', { name: /Критические проблемы: 2/ }).click()
  await expect(page.getByTestId('risks')).toBeVisible()
  await page.getByRole('button', { name: 'Настроить экран', exact: true }).click()
  await page.getByRole('button', { name: 'Скрыть блок: Команда', exact: true }).click()
  await page.getByRole('button', { name: 'Вернуть: Команда', exact: true }).click()
  await expect(page.locator('[data-widget-id="team"]')).toBeVisible()
  const beforeReset = await readLayout(page)
  await page.getByRole('button', { name: 'Сбросить расположение', exact: true }).click()
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  expect(await readLayout(page)).toEqual(beforeReset)
  await page.getByRole('button', { name: 'Сбросить расположение', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Сбросить расположение', exact: true }).click()
  expect((await readLayout(page)).widgets.find((item: { id: string }) => item.id === 'budget').width).toBe(2)
  expect(await readStore(page)).toEqual(storeBefore)
})

async function drag(page: Page, handle: Locator, target: Locator, position: 'before' | 'after') {
  await target.scrollIntoViewIfNeeded(); await handle.scrollIntoViewIfNeeded()
  const from = (await handle.boundingBox())!, to = (await target.boundingBox())!
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(from.x + from.width / 2 + 12, from.y + from.height / 2, { steps: 4 })
  await page.mouse.move(to.x + to.width / 2, to.y + to.height * (position === 'after' ? .7 : .3), { steps: 20 })
  // Auto-scroll can move the destination during the gesture. Finish over its current bounds.
  await target.evaluate(element => element.scrollIntoView({ block: 'center', behavior: 'instant' }))
  await target.hover({ position: { x: to.width / 2, y: to.height * (position === 'after' ? .7 : .3) } })
  await expect(page.getByText(/^(Место вставки|В конец этапа)$/).first()).toBeVisible()
  await page.mouse.up()
}

test('настоящее перетаскивание работает за ручки и не изменяет другие данные', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1500 })
  await page.goto('/#tasks')
  const before = (await readStore(page)).events[0]
  const second = page.getByTestId('task-row').filter({ has: page.getByRole('button', { name: 'Составить программу мастер-класса', exact: true }) })
  await drag(page, page.getByRole('button', { name: 'Перетащить: Определить тему и формат', exact: true }), second, 'after')
  await expect.poll(async () => (await readStore(page)).events[0].tasks.filter((task: { stageId: string }) => task.stageId === before.tasks[0].stageId)[0].title).toBe('Составить программу мастер-класса')
  const after = (await readStore(page)).events[0]
  for (const task of before.tasks) expect(after.tasks.find((item: { id: string | number }) => item.id === task.id)).toEqual(task)
  await page.getByRole('button', { name: 'Определить тему и формат', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  for (const name of ['Помещение', 'Программа', 'Материалы', 'Команда', 'День мероприятия']) await page.getByRole('button', { name: `Свернуть этап: ${name}`, exact: true }).click()
  const program = page.getByTestId('plan-stage').filter({ has: page.getByRole('heading', { name: 'Программа', exact: true }) })
  await drag(page, page.getByRole('button', { name: 'Перетащить: Помещение', exact: true }), program, 'after')
  await expect.poll(async () => (await readStore(page)).events[0].stages[0].title).toBe('Программа')
  const day = page.getByTestId('plan-stage').filter({ has: page.getByRole('heading', { name: 'День мероприятия', exact: true }) })
  await drag(page, page.getByRole('button', { name: 'Перетащить: Проверить оборудование', exact: true }), day, 'after')
  await expect.poll(async () => {
    const event = (await readStore(page)).events[0], task = event.tasks.find((task: { title: string }) => task.title === 'Проверить оборудование')
    return event.stages.find((stage: { id: string }) => stage.id === task.stageId).title
  }).toBe('День мероприятия')
  await page.goto('/')
  const planBefore = await readStore(page)
  await page.getByRole('button', { name: 'Настроить экран', exact: true }).click()
  for (const name of ['Антипровал', 'Бюджет', 'Команда']) await page.getByRole('button', { name: `Скрыть блок: ${name}`, exact: true }).click()
  await drag(page, page.getByRole('button', { name: 'Перетащить: Прогресс', exact: true }), page.locator('[data-widget-id="upcoming"]'), 'before')
  await expect.poll(async () => (await readLayout(page)).widgets.filter((item: { visible: boolean }) => item.visible).map((item: { id: string }) => item.id)).toEqual(['event', 'progress', 'upcoming'])
  expect(await readStore(page)).toEqual(planBefore)
})

