import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

test.beforeEach(async ({ page }) => { await page.clock.install({ time: new Date('2026-10-28T09:00:00Z') }) })
async function create(page: Page, title: string, template = 'empty', date = '2026-11-10') {
  await page.getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await page.getByLabel('Название мероприятия').fill(title)
  await page.getByLabel('Формат мероприятия').fill('Встреча команды')
  await page.getByLabel('Дата мероприятия').fill(date)
  await page.getByLabel('Начальный план').selectOption(template)
  await page.getByRole('dialog').getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
}
async function switchEvent(page: Page, title: string) { await page.locator('select[aria-label="Текущее мероприятие"]:visible').selectOption({ label: title }) }

test('задачи, расходы и команда изолированы по мероприятиям и сохраняются', async ({ page }) => {
  await page.goto('/')
  await create(page, 'Встреча команды')
  await expect(page.getByTestId('progress')).toContainText('0 из 0')
  await page.getByRole('button', { name: 'Команда мероприятия' }).click()
  await page.getByLabel('Имя участника 1', { exact: true }).fill('Анна')
  await page.getByRole('button', { name: 'Сохранить команду' }).click()
  await page.goto('/#tasks')
  await page.getByRole('button', { name: 'Добавить задачу', exact: true }).click()
  await page.getByLabel('Название задачи').fill('Согласовать список гостей')
  await page.getByLabel('Ответственный', { exact: true }).selectOption({ label: 'Анна' })
  await page.getByLabel('Срок выполнения').fill('2026-11-09')
  await page.getByLabel('Критическая задача', { exact: true }).check()
  await page.getByRole('button', { name: 'Сохранить изменения' }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.getByLabel('Фильтр по ответственному').selectOption({ label: 'Преподаватель' })
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  await page.getByLabel('Фильтр по ответственному').selectOption({ label: 'Анна' })
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.goto('/#budget')
  await page.getByRole('button', { name: 'Добавить расход' }).click()
  await page.getByLabel('Название статьи').fill('Аренда стульев')
  await page.getByLabel('План, ₽', { exact: true }).fill('500')
  await page.getByLabel('Остаток подтверждённых обязательств, ₽').fill('300')
  await page.getByLabel('Дополнительные ожидаемые расходы, ₽').fill('200')
  await page.getByRole('button', { name: 'Сохранить расходы' }).click()
  await expect(page.getByTestId('budget-total')).toContainText('500 ₽')
  await switchEvent(page, 'Открытый мастер-класс')
  await expect(page.getByTestId('progress')).toContainText('8 из 10')
  await expect(page.getByRole('button', { name: 'Команда мероприятия' })).not.toContainText('Анна')
  await page.goto('/#budget')
  await expect(page.getByTestId('budget-total')).toContainText('22 000')
  await expect(page.getByTestId('expense-row')).toHaveCount(6)
  await switchEvent(page, 'Встреча команды')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Команда мероприятия' })).toContainText('Анна')
  await page.goto('/#tasks')
  await expect(page.getByTestId('task-row')).toContainText('Согласовать список гостей')
  await page.goto('/#budget')
  await expect(page.getByTestId('budget-total')).toContainText('500 ₽')
})

test('оплата не удваивает итог и проверяет сумму', async ({ page }) => {
  await page.goto('/#budget')
  await page.getByRole('button', { name: 'Отметить оплату: Аренда помещения', exact: true }).click()
  await page.getByLabel('Сумма оплаты, ₽').fill('5000')
  await page.getByRole('button', { name: 'Учесть оплату' }).click()
  await expect(page.getByRole('alert')).toContainText('превышает остаток')
  await page.getByLabel('Сумма оплаты, ₽').fill('1500,25')
  await page.getByRole('button', { name: 'Учесть оплату' }).click()
  await expect(page.getByTestId('budget-total')).toContainText('22 000')
  const row = page.getByTestId('expense-row').filter({ hasText: 'Аренда помещения' })
  await expect(row.locator('[data-label="Оплачено"]')).toContainText('4 500,25')
  await expect(row.locator('[data-label="Остаток обязательств"]')).toContainText('2 499,75')
  await page.reload()
  await expect(row.locator('[data-label="Оплачено"]')).toContainText('4 500,25')
  await expect(page.getByTestId('budget-overrun')).toContainText('2 000')
})

