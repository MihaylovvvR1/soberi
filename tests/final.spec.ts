import { test, expect } from '@playwright/test'

test('полный сценарий записи: проблемы, расходы, частичная оплата, разделение и восстановление', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-29T09:00:00Z') })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Начать работу', exact: true }).click()
  await expect(page.getByTestId('progress')).toContainText('8 из 10')
  await page.getByRole('button', { name: 'Помещение не подтверждено: Подтвердить помещение', exact: true }).click()
  await page.getByLabel('Статус', { exact: true }).selectOption('done')
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await page.goto('/')
  await expect(page.locator('[data-risk-kind="venue"]')).toHaveCount(0)
  await expect(page.getByTestId('progress')).toContainText('9 из 10')
  await page.getByRole('button', { name: 'За оборудование никто не отвечает: Назначить ответственного', exact: true }).click()
  await page.getByLabel('Ответственный', { exact: true }).selectOption({ label: 'Помощник' })
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await page.goto('/')
  await expect(page.locator('[data-risk-kind="unassigned"]')).toHaveCount(0)
  await expect(page.getByTestId('progress')).toContainText('9 из 10')
  await page.goto('/#budget')
  await page.getByRole('button', { name: 'Изменить расход: Вода и кофе для участников', exact: true }).click()
  await page.getByLabel('Дополнительные ожидаемые расходы, ₽').fill('500')
  await page.getByRole('button', { name: 'Сохранить расходы', exact: true }).click()
  await expect(page.getByTestId('budget-total')).toContainText('20 000')
  await page.getByRole('button', { name: 'Отметить оплату: Аренда помещения', exact: true }).click()
  await page.getByLabel('Сумма оплаты, ₽').fill('1500')
  await page.getByRole('button', { name: 'Учесть оплату', exact: true }).click()
  await expect(page.getByTestId('budget-total')).toContainText('20 000')
  const rent = page.getByTestId('expense-row').filter({ hasText: 'Аренда помещения' })
  await expect(rent.locator('[data-label="Оплачено"]')).toContainText('4 500')
  await expect(rent.locator('[data-label="Остаток обязательств"]')).toContainText('2 500')
  await page.reload()
  await expect(page.getByTestId('budget-total')).toContainText('20 000')
  await page.getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await page.getByLabel('Название мероприятия').fill('Моё отдельное событие')
  await page.getByLabel('Начальный план').selectOption('empty')
  await page.getByRole('dialog').getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await expect(page.getByTestId('progress')).toContainText('0 из 0')
  await page.goto('/#budget')
  await expect(page.getByTestId('expense-row')).toHaveCount(0)
  await page.locator('select[aria-label="Текущее мероприятие"]:visible').selectOption('demo')
  await page.goto('/#tasks')
  await expect(page.getByTestId('task-row').filter({ hasText: 'Проверить оборудование' })).toContainText('Помощник')
  await page.getByRole('button', { name: 'Сохранить как шаблон', exact: true }).click()
  await page.getByLabel('Название шаблона').fill('Проверенный план')
  await page.getByRole('button', { name: 'Сохранить шаблон', exact: true }).click()
  await page.getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await page.getByLabel('Название мероприятия').fill('Событие по своему шаблону')
  await page.getByLabel('Начальный план').selectOption({ label: 'Проверенный план' })
  await page.getByLabel('Дата мероприятия').fill('2026-12-20')
  await page.getByRole('dialog').getByRole('button', { name: 'Создать мероприятие', exact: true }).click()
  await expect(page.getByTestId('progress')).toContainText('0 из 10')
  const snapshot = await page.evaluate(() => JSON.parse(localStorage.getItem('soberi-demo-v1')!))
  const clone = snapshot.events.find((event: { id: string }) => event.id === snapshot.activeId)
  expect(clone.tasks.every((task: { status: string }) => task.status === 'open')).toBeTruthy()
  expect(clone.expenses.every((expense: { paid: number; agreed: number }) => expense.paid === 0 && expense.agreed === 0)).toBeTruthy()
  await page.getByRole('button', { name: 'Восстановить пример', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Восстановить пример', exact: true }).click()
  await expect(page.getByTestId('progress')).toContainText('8 из 10')
  await expect(page.locator('[data-risk-kind="venue"]')).toHaveCount(1)
  await expect(page.locator('[data-risk-kind="unassigned"]')).toHaveCount(1)
  expect(await page.locator('select[aria-label="Текущее мероприятие"]:visible option').count()).toBe(3)
  await page.goto('/#budget')
  await expect(page.getByTestId('budget-total')).toContainText('22 000')
  expect(errors).toEqual([])
})
