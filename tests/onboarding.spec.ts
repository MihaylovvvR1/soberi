test('перенос ручкой работает под подсветкой и не меняет пользовательское расположение', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1500 })
  await page.goto('/')
  const before = await mainStore(page)
  await page.getByRole('button', { name: 'Обучение', exact: true }).click()
  await next(page); await next(page)
  await page.locator('[data-tour="assign-problem"]').click()
  await page.getByLabel('Ответственный', { exact: true }).selectOption({ label: 'Помощник' })
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Выполнить: Проверить оборудование', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 5 из 7')
  await next(page)
  await page.getByRole('button', { name: 'Настроить экран', exact: true }).click()
  const handle = page.getByRole('button', { name: 'Перетащить: Прогресс', exact: true })
  const target = page.locator('[data-widget-id="upcoming"]')
  const from = (await handle.boundingBox())!, to = (await target.boundingBox())!
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(from.x + from.width / 2 + 12, from.y + from.height / 2, { steps: 4 })
  await page.mouse.move(to.x + to.width / 2, to.y + 15, { steps: 15 })
  await expect(page.getByText('Место вставки', { exact: true })).toBeVisible()
  await page.mouse.up()
  await expect(tip(page)).toContainText('Шаг 7 из 7')
  expect(await mainStore(page)).toEqual(before)
  await tip(page).getByRole('button', { name: 'Пропустить', exact: true }).click()
})
