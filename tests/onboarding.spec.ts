import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

const tip = (page: Page) => page.getByRole('dialog', { name: 'Обучение СОБЕРИ', exact: true })
const next = (page: Page) => tip(page).getByRole('button', { name: 'Далее', exact: true }).click()
const mainStore = (page: Page) => page.evaluate(() => ({ events: JSON.parse(localStorage.getItem('soberi-demo-v1')!), layout: JSON.parse(localStorage.getItem('soberi-workspace-v1')!) }))

test('полное обучение проверяет действия и сохраняет реальные мероприятия и расположение', async ({ page }) => {
  await page.goto('/#budget')
  const original = await mainStore(page)
  await page.getByRole('button', { name: 'Пройти обучение', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 1 из 7')
  await next(page); await next(page)
  await expect(tip(page)).toContainText('Шаг 3 из 7')
  await expect(tip(page).getByRole('button', { name: 'Далее', exact: true })).toHaveCount(0)
  await page.locator('[data-tour="assign-problem"]').click()
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 3 из 7')
  await page.locator('[data-tour="assign-problem"]').click()
  await page.getByLabel('Ответственный', { exact: true }).selectOption({ label: 'Помощник' })
  await expect(tip(page)).toContainText('Шаг 3 из 7')
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 4 из 7')
  await page.getByRole('button', { name: 'Проверить оборудование', exact: true }).click()
  await page.getByLabel('Статус', { exact: true }).selectOption('done')
  await expect(tip(page)).toContainText('Шаг 4 из 7')
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 5 из 7')
  await expect(page.getByTestId('budget-total')).toContainText('22 000')
  await next(page)
  await page.getByRole('button', { name: 'Настроить экран', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 6 из 7')
  await page.getByRole('button', { name: 'Выше блок: Прогресс', exact: true }).click()
  await expect(tip(page)).toContainText('Шаг 7 из 7')
  await page.getByLabel('Тема оформления', { exact: true }).selectOption('dark')
  await tip(page).getByRole('button', { name: 'Завершить обучение', exact: true }).click()
  await expect(tip(page)).toHaveCount(0)
  await expect(page).toHaveURL(/#budget$/)
  expect(await mainStore(page)).toEqual(original)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('soberi-onboarding-v1')!).status)).toBe('completed')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Пройти обучение', exact: true })).toHaveCount(0)
})

